#!/usr/bin/env python3
"""Roofline decision check: predicted pull/recompute vs. the measured winner per cell.

Reads results/sweep_all.csv (dgl vs split, 0% cache, the Section-1 protocol), and for each
(graph, hardware, model, depth, hidden) cell reports
  * measured winner by TRAINING-ONLY time (forward+backward)  -- the fair comparison for the
    roofline, which prices compute + shuffle only
  * measured winner by PER-EPOCH time (duration)              -- for reference
  * the roofline's prediction with the CURRENT constants in gen_roofline.py
    (pull=split if T_cmp > T_net at that model/h/interconnect, else recompute=DP)
Emits tables/roofline_validation.tex. Light CPU, local-only.
  python3 defense_latex/gen_roofline_validation.py
"""
import os
import sys
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_roofline as gr  # noqa: E402  (constants + per-node demands)

HW_KEY = {"pcie_emu": "PCIe-emu", "nvlink": "NVLink"}


def predict(model, h, hardware):
    r = gr.row(model.upper(), int(h))
    t_net = r["t_net"][HW_KEY[hardware]]
    ratio = t_net / r["t_cmp"]
    return ("split" if r["t_cmp"] > t_net else "dgl"), ratio


def main():
    df = pd.read_csv(os.path.join(HERE, "results", "sweep_all.csv"))
    df = df[df["system"].isin(["dgl", "split"])]
    df = df[df["cache_size"].isin(["0G", "0GB"])]          # Section-1 protocol: no feature cache
    df["depth"] = df["fanouts"].str.count(",") + 1
    for col in ("forward (s)", "backward (s)", "duration (s)"):
        df[col] = pd.to_numeric(df[col], errors="coerce")   # T/O, OOM markers -> NaN
    df["train"] = df["forward (s)"] + df["backward (s)"]
    keys = ["graph_name", "hardware", "model", "depth", "hid_size"]
    agg = (df.groupby(keys + ["system"])[["train", "duration (s)"]].mean()
             .unstack("system"))
    agg = agg.dropna()                                        # cells with both systems
    agg.columns = [f"{m}_{s}" for m, s in agg.columns]
    agg = agg.reset_index().sort_values(keys)

    lines = [
        "% AUTO-GENERATED by gen_roofline_validation.py -- edit the script, not this file.",
        "\\begin{table}[h]",
        "\\centering",
        "\\caption{Decision check with the \\emph{current} (peak-rate) constants: the roofline's "
        "per-layer verdict---pull (split) if $T^{\\mathrm{cmp}}>T^{\\mathrm{net}}$, else recompute "
        "(DGL/data parallel)---against the measured winner per cell (4$\\times$A100, no feature "
        "cache, mean over runs). Train $=$ forward$+$backward, the quantity the roofline prices; "
        "epoch $=$ per-epoch duration for reference. $T^{\\mathrm{net}}/T^{\\mathrm{cmp}}$ is the "
        "model's ratio for that (model, $h$, interconnect). \\checkmark{} $=$ prediction matches the "
        "train-only winner.}",
        "\\label{tab:roofline-validation}",
        "\\footnotesize\\setlength{\\tabcolsep}{4pt}",
        "\\resizebox{\\linewidth}{!}{%",
        "\\begin{tabular}{l l l r r | r r | r r | l l | c l}",
        "\\toprule",
        "graph & hw & model & $L$ & $h$ & split train & DGL train & split epoch & DGL epoch & "
        "win (train) & win (epoch) & pred & $T^{\\mathrm{net}}/T^{\\mathrm{cmp}}$ \\\\",
        "\\midrule",
    ]
    n_ok = 0
    by_hw = {}
    last = None
    for _, c in agg.iterrows():
        pred, ratio = predict(c["model"], c["hid_size"], c["hardware"])
        win_t = "split" if c["train_split"] < c["train_dgl"] else "dgl"
        win_e = "split" if c["duration (s)_split"] < c["duration (s)_dgl"] else "dgl"
        ok = pred == win_t
        n_ok += ok
        by_hw.setdefault(c["hardware"], [0, 0])
        by_hw[c["hardware"]][0] += ok
        by_hw[c["hardware"]][1] += 1
        grp = (c["graph_name"], c["hardware"])
        if last and grp != last:
            lines.append("\\midrule")
        last = grp
        lines.append(
            f"{c['graph_name']} & {HW_KEY[c['hardware']]} & {c['model']} & {int(c['depth'])} & "
            f"{int(c['hid_size'])} & {c['train_split']:.1f} & {c['train_dgl']:.1f} & "
            f"{c['duration (s)_split']:.1f} & {c['duration (s)_dgl']:.1f} & {win_t} & {win_e} & "
            f"{'\\checkmark' if ok else '$\\times$'} {pred} & {ratio:.2g} \\\\")
    lines += [
        "\\midrule",
        f"\\multicolumn{{13}}{{l}}{{agreement with the train-only winner: {n_ok}/{len(agg)} cells ("
        + "; ".join(f"{HW_KEY[k]} {v[0]}/{v[1]}" for k, v in by_hw.items()) + ")} \\\\",
        "\\bottomrule",
        "\\end{tabular}}",
        "\\end{table}",
        "",
    ]
    out = os.path.join(HERE, "tables", "roofline_validation.tex")
    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    print("wrote", out, f"({len(agg)} cells, {n_ok} agree)", by_hw)


if __name__ == "__main__":
    main()
