#!/usr/bin/env python3
"""Roofline numbers for the analytical redundancy model (Section: roofline).

Pure python, no deps. Emits
  tables/roofline_instances.tex   numeric F, S, C, intensities, times for SAGE/GAT at h in HS
  figures/roofline.tex            pgfplots nested roofline (standalone tikzpicture, slide-ready)

All per DESTINATION NODE, per LAYER, forward+backward, fp32.
Edit the PARAMETERS block and re-run:  python3 defense_latex/gen_roofline.py
"""
import os

# ----------------------------- PARAMETERS ---------------------------------
B      = 4          # bytes per feature value (fp32)
F_OUT  = 15         # fanout (sampled in-degree d_v, upper bound f)
HEADS  = 4          # GAT heads
RHO    = 6          # GAT frontier expansion n_src/n_dst (block avg; per-node bound = f)
SIGMA  = 10         # GAT head-wide (H-scalar) edge passes fwd+bwd (u_add_v, leaky, softmax)
HS     = [256, 1024, 4096]

P      = 19.5e12    # A100 fp32 SIMT peak (ampere_sgemm; TF32 off in torch.matmul)
B_MEM  = 2.0e12     # A100-SXM-80GB HBM2e peak
# Effective per-GPU two-way all-to-all shuffle bandwidth. PRELIMINARY: derived
# from the shuffle isolated by subtraction (PCIe-emu minus NVLink fwd+bwd at
# fixed compute); emulated PCIe => directional only. Refine with a direct
# 4-GPU all-to-all microbenchmark.
B_NET  = {"PCIe-emu": 1.0e9, "NVLink": 54e9}
# ---------------------------------------------------------------------------

HERE = os.path.dirname(os.path.abspath(__file__))


def demands(model, h):
    """Return (F flops, S dram bytes, C pulled bytes) per dst node per layer."""
    if model == "SAGE":
        F = 12 * h * h                       # 2 GEMMs on dst rows x {fwd, dX, dW}
        S = (2 * F_OUT + 12) * h * B         # 2 h-wide edge passes + 6 GEMM row-passes
    else:  # GAT
        F = 6 * RHO * h * h                  # 1 GEMM on src rows (rho per dst) x 3
        S = (4 * F_OUT + 6 * RHO) * h * B + SIGMA * F_OUT * HEADS * B
    C = 2 * h * B                            # pull one row in (fwd) + one grad out (bwd)
    return F, S, C


def row(model, h):
    F, S, C = demands(model, h)
    t_flop = F / P
    t_mem = S / B_MEM
    t_cmp = t_flop + t_mem
    p_eff = F / t_cmp
    i_mem = F / S
    i_net = F / C
    t_net = {k: C / v for k, v in B_NET.items()}
    return dict(model=model, h=h, F=F, S=S, C=C, t_flop=t_flop, t_mem=t_mem,
                t_cmp=t_cmp, p_eff=p_eff, i_mem=i_mem, i_net=i_net, t_net=t_net)


ROWS = [row(m, h) for m in ("SAGE", "GAT") for h in HS]


def fmt_si(x, unit):
    for p, s in ((1e9, "G"), (1e6, "M"), (1e3, "k")):
        if x >= p:
            return f"{x / p:.3g}\\,{s}{unit}"
    return f"{x:.3g}\\,{unit}"


def fmt_t(sec):
    if sec >= 1e-6:
        return f"{sec * 1e6:.2f}\\,\\si{{\\micro\\second}}"
    return f"{sec * 1e9:.0f}\\,ns"


def write_table():
    nets = list(B_NET)
    lines = [
        "% AUTO-GENERATED by gen_roofline.py -- edit the script, not this file.",
        "\\begin{table}[h]",
        "\\centering",
        "\\caption{Roofline demands and bounds per destination node per layer "
        "(forward$+$backward, fp32, fanout $f{=}%d$, GAT $H{=}%d$, $\\rho{=}%d$). "
        "$T^{\\mathrm{cmp}}=F/P+S/B_{\\mathrm{mem}}$ at A100 peak ($P{=}%.1f$\\,TFLOP/s, "
        "$B_{\\mathrm{mem}}{=}%.1f$\\,TB/s); $T^{\\mathrm{net}}=C/B_{\\mathrm{net}}$ with "
        "effective $B_{\\mathrm{net}}$ of %s.}"
        % (F_OUT, HEADS, RHO, P / 1e12, B_MEM / 1e12,
           ", ".join(f"{k} {v / 1e9:.3g}\\,GB/s" for k, v in B_NET.items())),
        "\\label{tab:roofline-instances}",
        "\\footnotesize\\setlength{\\tabcolsep}{3.5pt}",
        "\\resizebox{\\linewidth}{!}{%",
        "\\begin{tabular}{l r | r r r | r r | r r | r r}",
        "\\toprule",
        "Model & $h$ & $F$ & $S$ & $C$ & $I^{\\mathrm{mem}}$ & $I^{\\mathrm{net}}$ & "
        "$T^{\\mathrm{cmp}}$ & $P_{\\mathrm{eff}}$ & "
        + " & ".join(f"$T^{{\\mathrm{{net}}}}_{{\\text{{{n}}}}}$" for n in nets) + " \\\\",
        " & & (FLOP) & (B) & (B) & (FLOP/B) & (FLOP/B) & & (TFLOP/s) & "
        + " & ".join(["(ratio to $T^{\\mathrm{cmp}}$)"] * len(nets)) + " \\\\",
        "\\midrule",
    ]
    last = None
    for r in ROWS:
        if last and r["model"] != last:
            lines.append("\\midrule")
        last = r["model"]
        tn = " & ".join(f"{fmt_t(r['t_net'][n])} ({r['t_net'][n] / r['t_cmp']:.2g}$\\times$)"
                        for n in nets)
        lines.append(
            f"{r['model']} & {r['h']} & {fmt_si(r['F'], 'FLOP')} & {fmt_si(r['S'], 'B')} & "
            f"{fmt_si(r['C'], 'B')} & {r['i_mem']:.0f} & {r['i_net']:.0f} & "
            f"{fmt_t(r['t_cmp'])} & {r['p_eff'] / 1e12:.1f} & {tn} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}}", "\\end{table}", ""]
    out = os.path.join(HERE, "tables", "roofline_instances.tex")
    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    print("wrote", out)


def write_figure():
    xmin, xmax = 1e2, 1e5
    ymin, ymax = 1e11, 4e13
    lines = [
        "% AUTO-GENERATED by gen_roofline.py -- edit the script, not this file.",
        "% Standalone tikzpicture: \\input it in the thesis or a beamer slide",
        "% (needs \\usepackage{pgfplots} \\pgfplotsset{compat=1.18}).",
        "\\begin{tikzpicture}",
        "\\begin{loglogaxis}[",
        "  width=0.9\\linewidth, height=0.58\\linewidth,",
        f"  xmin={xmin:g}, xmax={xmax:g}, ymin={ymin:g}, ymax={ymax:g},",
        "  xlabel={network intensity $I^{\\mathrm{net}} = F/C$ (FLOP per shuffled byte)},",
        "  ylabel={attainable rate (FLOP/s)},",
        "  grid=major, grid style={gray!25},",
        "  legend style={at={(0.02,0.98)}, anchor=north west, font=\\footnotesize, "
        "cells={anchor=west}},",
        "  tick label style={font=\\footnotesize}, label style={font=\\small},",
        "]",
        # compute roof
        f"\\addplot[very thick, black] coordinates {{({xmin:g},{P:g}) ({xmax:g},{P:g})}};",
        "\\addlegendentry{dense roof $P$ (A100 fp32 peak)}",
    ]
    styles = {"PCIe-emu": "red!80!black", "NVLink": "blue!70!black"}
    for name, bw in B_NET.items():
        ridge = P / bw
        x0 = max(xmin, ymin / bw)
        lines.append(
            f"\\addplot[very thick, {styles[name]}] coordinates "
            f"{{({x0:g},{x0 * bw:g}) ({ridge:g},{P:g})}};")
        lines.append(f"\\addlegendentry{{shuffle roof, {name} ($B_{{\\mathrm{{net}}}}{{=}}{bw / 1e9:.3g}$\\,GB/s)}}")
        lines.append(
            f"\\addplot[dashed, {styles[name]}, thin] coordinates "
            f"{{({ridge:g},{ymin:g}) ({ridge:g},{P:g})}};")
        lines.append(
            f"\\node[{styles[name]}, font=\\scriptsize, anchor=south, rotate=90] at "
            f"(axis cs:{ridge:g},{ymin * 3:g}) {{ridge {name}}};")
    # points: (I_net, P_eff) per model/h
    marks = {"SAGE": "*", "GAT": "square*"}
    for model in ("SAGE", "GAT"):
        pts = " ".join(f"({r['i_net']:g},{r['p_eff']:g})" for r in ROWS if r["model"] == model)
        lines.append(
            f"\\addplot[only marks, mark={marks[model]}, mark size=2.6pt, black] coordinates {{{pts}}};")
        lines.append(f"\\addlegendentry{{{model} at $h\\in\\{{{','.join(map(str, HS))}\\}}$}}")
        for r in ROWS:
            if r["model"] == model:
                tag = f"{model[0]}{r['h'] // 1024 if r['h'] >= 1024 else r['h']}{'k' if r['h'] >= 1024 else ''}"
                anchor = "north" if model == "SAGE" else "south"
                lines.append(
                    f"\\node[font=\\scriptsize, anchor={anchor}, inner sep=1.5pt] at "
                    f"(axis cs:{r['i_net']:g},{r['p_eff']:g}) {{{tag}}};")
    lines += [
        f"\\node[font=\\scriptsize, anchor=south east, align=right] at (axis cs:{xmax * 0.9:g},{ymin * 1.3:g}) "
        "{left of a ridge: comm-bound $\\Rightarrow$ recompute\\\\right of a ridge: compute-bound $\\Rightarrow$ pull};",
        "\\end{loglogaxis}",
        "\\end{tikzpicture}",
        "",
    ]
    out = os.path.join(HERE, "figures", "roofline.tex")
    with open(out, "w") as fh:
        fh.write("\n".join(lines))
    print("wrote", out)


if __name__ == "__main__":
    write_table()
    write_figure()
    for r in ROWS:
        print(f"{r['model']:4s} h={r['h']:5d} F={r['F']:.3g} S={r['S']:.3g} C={r['C']:.3g} "
              f"Imem={r['i_mem']:.1f} Inet={r['i_net']:.0f} Tcmp={r['t_cmp'] * 1e9:.0f}ns "
              f"Peff={r['p_eff'] / 1e12:.1f}TF " +
              " ".join(f"{k}:{v / r['t_cmp']:.2g}x" for k, v in r['t_net'].items()))
    for k, v in B_NET.items():
        print(f"ridge {k}: {P / v:.0f} FLOP/B")
